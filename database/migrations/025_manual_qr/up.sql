CREATE TABLE nd_manual_qr_versions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 storage_key CHAR(64) NOT NULL UNIQUE,
 mime VARCHAR(32) NOT NULL,
 size_bytes BIGINT UNSIGNED NOT NULL,
 checksum CHAR(64) NOT NULL,
 recipient_name VARCHAR(190) NOT NULL,
 verified_at DATETIME NULL,
 verified_by TINYINT UNSIGNED NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(verified_by) REFERENCES nd_admin(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_manual_qr_settings (
 id TINYINT UNSIGNED PRIMARY KEY,
 current_version_id BIGINT UNSIGNED NULL,
 enabled TINYINT UNSIGNED NOT NULL DEFAULT 0,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 FOREIGN KEY(current_version_id) REFERENCES nd_manual_qr_versions(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_manual_qr_assignments (
 invoice_id BIGINT UNSIGNED PRIMARY KEY,
 qr_version_id BIGINT UNSIGNED NOT NULL,
 invoice_snapshot_hash CHAR(64) NOT NULL,
 released_by TINYINT UNSIGNED NOT NULL,
 released_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(invoice_id) REFERENCES nd_invoices(id) ON DELETE RESTRICT,
 FOREIGN KEY(qr_version_id) REFERENCES nd_manual_qr_versions(id) ON DELETE RESTRICT,
 FOREIGN KEY(released_by) REFERENCES nd_admin(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
