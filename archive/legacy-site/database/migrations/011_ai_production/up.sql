-- Production metadata only; reuse AI, CRM, files, quote and customer identities.
CREATE TABLE nd_prod_rate_scopes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 rate_id BIGINT UNSIGNED NOT NULL,
 service_type VARCHAR(32) NOT NULL,
 active TINYINT UNSIGNED NOT NULL,
 verified_at DATETIME NOT NULL,
 source VARCHAR(500) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY nd_prod_rate_scope(rate_id,service_type,id),
 FOREIGN KEY (rate_id) REFERENCES nd_cost_rates(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_prod_plans (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 project_id BIGINT UNSIGNED NOT NULL,
 order_id BIGINT UNSIGNED NOT NULL,
 customer_id BIGINT UNSIGNED NOT NULL,
 spec_revision_id BIGINT UNSIGNED NOT NULL,
 quotation_id BIGINT UNSIGNED NOT NULL,
 revision_number INT UNSIGNED NOT NULL,
 previous_id BIGINT UNSIGNED NULL,
 ai_artifact_id BIGINT UNSIGNED NULL,
 service_type VARCHAR(32) NOT NULL,
 body MEDIUMTEXT NOT NULL,
 checksum CHAR(64) NOT NULL,
 source_json MEDIUMTEXT NOT NULL,
 source_hash CHAR(64) NOT NULL,
 state VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
 version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY nd_prod_plan_revision(project_id,revision_number),
 FOREIGN KEY (project_id) REFERENCES nd_projects(id) ON DELETE RESTRICT,
 FOREIGN KEY (customer_id,order_id) REFERENCES nd_orders(customer_id,id) ON DELETE RESTRICT,
 FOREIGN KEY (spec_revision_id) REFERENCES nd_cc_revisions(id) ON DELETE RESTRICT,
 FOREIGN KEY (quotation_id) REFERENCES nd_quotations(id) ON DELETE RESTRICT,
 FOREIGN KEY (previous_id) REFERENCES nd_prod_plans(id) ON DELETE RESTRICT,
 FOREIGN KEY (ai_artifact_id) REFERENCES nd_ai_artifacts(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_prod_runs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 plan_id BIGINT UNSIGNED NOT NULL UNIQUE,
 state VARCHAR(32) NOT NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 revision_cycles TINYINT UNSIGNED NOT NULL DEFAULT 0,
 planning_estimated_micro BIGINT UNSIGNED NOT NULL DEFAULT 0,
 last_error VARCHAR(64) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (plan_id) REFERENCES nd_prod_plans(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_prod_steps (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 run_id BIGINT UNSIGNED NOT NULL,
 step_key VARCHAR(32) NOT NULL,
 agent_id VARCHAR(32) NOT NULL,
 state VARCHAR(32) NOT NULL,
 revision_number TINYINT UNSIGNED NOT NULL DEFAULT 1,
 ai_task_id BIGINT UNSIGNED NULL UNIQUE,
 budget_total_micro BIGINT UNSIGNED NOT NULL DEFAULT 0,
 pending_key CHAR(64) NULL,
 pending_micro BIGINT UNSIGNED NULL,
 last_error VARCHAR(64) NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 UNIQUE KEY nd_prod_step_key(run_id,step_key),
 UNIQUE KEY nd_prod_step_run(run_id,id),
 FOREIGN KEY (run_id) REFERENCES nd_prod_runs(id) ON DELETE RESTRICT,
 FOREIGN KEY (ai_task_id) REFERENCES nd_ai_tasks(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_prod_dependencies (
 run_id BIGINT UNSIGNED NOT NULL,
 step_id BIGINT UNSIGNED NOT NULL,
 predecessor_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY (step_id,predecessor_id),
 FOREIGN KEY (run_id,step_id) REFERENCES nd_prod_steps(run_id,id) ON DELETE RESTRICT,
 FOREIGN KEY (run_id,predecessor_id) REFERENCES nd_prod_steps(run_id,id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_prod_step_attempts (
 step_id BIGINT UNSIGNED NOT NULL,
 revision_number TINYINT UNSIGNED NOT NULL,
 ai_task_id BIGINT UNSIGNED NOT NULL UNIQUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(step_id,revision_number),
 FOREIGN KEY (step_id) REFERENCES nd_prod_steps(id) ON DELETE RESTRICT,
 FOREIGN KEY (ai_task_id) REFERENCES nd_ai_tasks(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_prod_artifacts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 step_id BIGINT UNSIGNED NOT NULL,
 revision_number TINYINT UNSIGNED NOT NULL,
 ai_artifact_id BIGINT UNSIGNED NOT NULL UNIQUE,
 files_json MEDIUMTEXT NOT NULL,
 checksum CHAR(64) NOT NULL,
 contract_json TEXT NOT NULL,
 execution_status VARCHAR(32) NOT NULL DEFAULT 'DRAFT_ONLY',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY nd_prod_artifact_revision(step_id,revision_number),
 FOREIGN KEY (step_id) REFERENCES nd_prod_steps(id) ON DELETE RESTRICT,
 FOREIGN KEY (ai_artifact_id) REFERENCES nd_ai_artifacts(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_prod_qa_reports (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 run_id BIGINT UNSIGNED NOT NULL,
 ai_task_id BIGINT UNSIGNED NOT NULL UNIQUE,
 bundle_hash CHAR(64) NOT NULL,
 verdict VARCHAR(32) NOT NULL,
 checks_json MEDIUMTEXT NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (run_id) REFERENCES nd_prod_runs(id) ON DELETE RESTRICT,
 FOREIGN KEY (ai_task_id) REFERENCES nd_ai_tasks(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_prod_findings (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 report_id BIGINT UNSIGNED NOT NULL,
 requirement_id VARCHAR(32) NOT NULL,
 method VARCHAR(64) NOT NULL,
 result VARCHAR(32) NOT NULL,
 severity VARCHAR(16) NOT NULL,
 description VARCHAR(1000) NOT NULL,
 evidence VARCHAR(500) NOT NULL,
 correction VARCHAR(1000) NOT NULL,
 retest_required TINYINT UNSIGNED NOT NULL,
 FOREIGN KEY (report_id) REFERENCES nd_prod_qa_reports(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_prod_revisions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 run_id BIGINT UNSIGNED NOT NULL,
 report_id BIGINT UNSIGNED NOT NULL,
 cycle TINYINT UNSIGNED NOT NULL,
 reason VARCHAR(1000) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY nd_prod_revision_cycle(run_id,cycle),
 FOREIGN KEY (run_id) REFERENCES nd_prod_runs(id) ON DELETE RESTRICT,
 FOREIGN KEY (report_id) REFERENCES nd_prod_qa_reports(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_prod_packages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 run_id BIGINT UNSIGNED NOT NULL,
 report_id BIGINT UNSIGNED NOT NULL,
 bundle_hash CHAR(64) NOT NULL,
 manifest_hash CHAR(64) NOT NULL UNIQUE,
 file_id BIGINT UNSIGNED NOT NULL UNIQUE,
 state VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
 version INT UNSIGNED NOT NULL DEFAULT 1,
 revision_id BIGINT UNSIGNED NULL UNIQUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (run_id) REFERENCES nd_prod_runs(id) ON DELETE RESTRICT,
 FOREIGN KEY (report_id) REFERENCES nd_prod_qa_reports(id) ON DELETE RESTRICT,
 FOREIGN KEY (file_id) REFERENCES nd_cc_files(id) ON DELETE RESTRICT,
 FOREIGN KEY (revision_id) REFERENCES nd_cc_revisions(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_prod_decisions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 entity ENUM('plan','package') NOT NULL,
 record_id BIGINT UNSIGNED NOT NULL,
 owner_id TINYINT UNSIGNED NOT NULL,
 decision ENUM('approved','rejected') NOT NULL,
 checksum CHAR(64) NOT NULL,
 source_hash CHAR(64) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY nd_prod_exact_decision(entity,record_id),
 FOREIGN KEY (owner_id) REFERENCES nd_admin(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_prod_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 run_id BIGINT UNSIGNED NULL,
 plan_id BIGINT UNSIGNED NOT NULL,
 category VARCHAR(64) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (run_id) REFERENCES nd_prod_runs(id) ON DELETE RESTRICT,
 FOREIGN KEY (plan_id) REFERENCES nd_prod_plans(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_prod_expenses (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 run_id BIGINT UNSIGNED NOT NULL,
 category VARCHAR(32) NOT NULL,
 amount_minor BIGINT UNSIGNED NOT NULL,
 currency CHAR(3) NOT NULL,
 hours_milli BIGINT UNSIGNED NULL,
 provenance ENUM('owner_entered','verified') NOT NULL,
 owner_id TINYINT UNSIGNED NOT NULL,
 source VARCHAR(1000) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY nd_prod_expense_latest(run_id,category,id),
 FOREIGN KEY (run_id) REFERENCES nd_prod_runs(id) ON DELETE RESTRICT,
 FOREIGN KEY (owner_id) REFERENCES nd_admin(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_prod_profitability (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 run_id BIGINT UNSIGNED NOT NULL,
 body MEDIUMTEXT NOT NULL,
 checksum CHAR(64) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (run_id) REFERENCES nd_prod_runs(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
