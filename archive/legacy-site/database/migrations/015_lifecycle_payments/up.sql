CREATE TABLE nd_lc_schedule_entries (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT UNSIGNED NOT NULL,
 binding_id BIGINT UNSIGNED NOT NULL,
 position SMALLINT UNSIGNED NOT NULL,
 label VARCHAR(190) NOT NULL,
 amount_minor BIGINT UNSIGNED NOT NULL,
 due_on DATE NOT NULL,
 gate ENUM('production','milestone','acceptance','handover','closure','none') NOT NULL,
 stage_id BIGINT UNSIGNED NULL,
 invoice_id BIGINT UNSIGNED NOT NULL UNIQUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY nd_lc_schedule_position(order_id,position),
 FOREIGN KEY (order_id) REFERENCES nd_orders(id) ON DELETE RESTRICT,
 FOREIGN KEY (binding_id) REFERENCES nd_lc_document_bindings(id) ON DELETE RESTRICT,
 FOREIGN KEY (stage_id) REFERENCES nd_project_stages(id) ON DELETE RESTRICT,
 FOREIGN KEY (invoice_id) REFERENCES nd_invoices(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_lc_payment_claims (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 invoice_id BIGINT UNSIGNED NOT NULL,
 account_id BIGINT UNSIGNED NOT NULL,
 amount_minor BIGINT UNSIGNED NOT NULL,
 paid_at DATETIME NOT NULL,
 payer VARCHAR(190) NOT NULL,
 reference VARCHAR(190) NOT NULL,
 file_id BIGINT UNSIGNED NULL,
 state ENUM('REPORTED','RECONCILED','REJECTED') NOT NULL DEFAULT 'REPORTED',
 matched_attempt_id BIGINT UNSIGNED NULL,
 reason TEXT NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (invoice_id) REFERENCES nd_invoices(id) ON DELETE RESTRICT,
 FOREIGN KEY (account_id) REFERENCES nd_customer_accounts(id) ON DELETE RESTRICT,
 FOREIGN KEY (file_id) REFERENCES nd_cc_files(id) ON DELETE RESTRICT,
 FOREIGN KEY (matched_attempt_id) REFERENCES nd_payment_attempts(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_lc_bank_records (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 transaction_id BIGINT UNSIGNED NULL UNIQUE,
 refund_id BIGINT UNSIGNED NULL UNIQUE,
 bank_entry_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 bank_reference VARCHAR(190) NOT NULL,
 payer VARCHAR(190) NOT NULL,
 paid_at DATETIME NOT NULL,
 method ENUM('cash','electronic','bank_other') NOT NULL,
 evidence_file_id BIGINT UNSIGNED NULL,
 reason TEXT NOT NULL,
 verified_by TINYINT UNSIGNED NOT NULL,
 evidence_source ENUM('OWNER_ATTESTED') NOT NULL DEFAULT 'OWNER_ATTESTED',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (transaction_id) REFERENCES nd_payment_transactions(id) ON DELETE RESTRICT,
 FOREIGN KEY (refund_id) REFERENCES nd_refunds(id) ON DELETE RESTRICT,
 FOREIGN KEY (evidence_file_id) REFERENCES nd_cc_files(id) ON DELETE RESTRICT,
 FOREIGN KEY (verified_by) REFERENCES nd_admin(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_lc_receipt_tasks (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 transaction_id BIGINT UNSIGNED NOT NULL UNIQUE,
 order_id BIGINT UNSIGNED NOT NULL,
 amount_minor BIGINT UNSIGNED NOT NULL,
 paid_at DATETIME NOT NULL,
 method ENUM('cash','electronic','bank_other') NOT NULL,
 buyer_type ENUM('person','ip','company') NOT NULL,
 buyer_inn VARCHAR(12) NULL,
 service_description VARCHAR(500) NOT NULL,
 due_at DATETIME NOT NULL,
 rule_version VARCHAR(64) NOT NULL,
 state ENUM('MISSING','OWNER_RECORDED','TRANSMISSION_RECORDED','CORRECTION_NEEDED') NOT NULL DEFAULT 'MISSING',
 version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (transaction_id) REFERENCES nd_payment_transactions(id) ON DELETE RESTRICT,
 FOREIGN KEY (order_id) REFERENCES nd_orders(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_lc_receipt_evidence (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 task_id BIGINT UNSIGNED NOT NULL,
 action ENUM('ISSUANCE_RECORDED','TRANSMISSION_RECORDED','CORRECTION_RECORDED','REFUND_REVIEW_REQUIRED') NOT NULL,
 official_url TEXT NULL,
 file_id BIGINT UNSIGNED NULL,
 external_reference VARCHAR(190) NULL,
 issued_at DATETIME NULL,
 transmitted_at DATETIME NULL,
 transmission_channel VARCHAR(32) NULL,
 refund_id BIGINT UNSIGNED NULL,
 reason TEXT NOT NULL,
 recorded_by TINYINT UNSIGNED NOT NULL,
 evidence_source ENUM('OWNER_ATTESTED') NOT NULL DEFAULT 'OWNER_ATTESTED',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (task_id) REFERENCES nd_lc_receipt_tasks(id) ON DELETE RESTRICT,
 FOREIGN KEY (file_id) REFERENCES nd_cc_files(id) ON DELETE RESTRICT,
 FOREIGN KEY (refund_id) REFERENCES nd_refunds(id) ON DELETE RESTRICT,
 FOREIGN KEY (recorded_by) REFERENCES nd_admin(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
