CREATE TABLE nd_lc_order_flow (
 order_id BIGINT UNSIGNED PRIMARY KEY,
 project_id BIGINT UNSIGNED NOT NULL UNIQUE,
 commercial_state ENUM('INQUIRY','QUALIFIED','BRIEF_READY','PRICE_APPROVED','PROPOSAL_SENT','PROPOSAL_ACCEPTED') NOT NULL DEFAULT 'INQUIRY',
 delivery_state ENUM('WAITING_MATERIALS','IN_PRODUCTION','OWNER_REVIEW','CLIENT_REVIEW','READY_HANDOVER','HANDOVER_PREPARED','HANDED_OVER') NOT NULL DEFAULT 'WAITING_MATERIALS',
 acceptance_state ENUM('PENDING','REVIEW','CHANGES_REQUESTED','ACCEPTED') NOT NULL DEFAULT 'PENDING',
 case_state ENUM('ACTIVE','PAUSED','DISPUTED','CANCELLED','DECLINED','CLOSED') NOT NULL DEFAULT 'ACTIVE',
 brief_revision_id BIGINT UNSIGNED NULL,
 quotation_id BIGINT UNSIGNED NULL,
 proposal_binding_id BIGINT UNSIGNED NULL,
 agreement_binding_id BIGINT UNSIGNED NULL,
 final_manifest MEDIUMTEXT NULL,
 final_hash CHAR(64) NULL,
 handover_hash CHAR(64) NULL,
 support_terms TEXT NULL,
 support_start DATE NULL,
 support_end DATE NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (order_id) REFERENCES nd_orders(id) ON DELETE RESTRICT,
 FOREIGN KEY (project_id) REFERENCES nd_projects(id) ON DELETE RESTRICT,
 FOREIGN KEY (brief_revision_id) REFERENCES nd_cc_revisions(id) ON DELETE RESTRICT,
 FOREIGN KEY (quotation_id) REFERENCES nd_quotations(id) ON DELETE RESTRICT,
 FOREIGN KEY (proposal_binding_id) REFERENCES nd_lc_document_bindings(id) ON DELETE RESTRICT,
 FOREIGN KEY (agreement_binding_id) REFERENCES nd_lc_document_bindings(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_lc_obligations (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT UNSIGNED NOT NULL,
 kind ENUM('MATERIAL','HANDOVER') NOT NULL,
 title VARCHAR(190) NOT NULL,
 details TEXT NOT NULL,
 required TINYINT UNSIGNED NOT NULL DEFAULT 1,
 state ENUM('MISSING','SUBMITTED','VERIFIED','NOT_APPLICABLE') NOT NULL DEFAULT 'MISSING',
 file_id BIGINT UNSIGNED NULL,
 verification_reason TEXT NULL,
 verified_by TINYINT UNSIGNED NULL,
 verified_at DATETIME NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (order_id) REFERENCES nd_lc_order_flow(order_id) ON DELETE RESTRICT,
 FOREIGN KEY (file_id) REFERENCES nd_cc_files(id) ON DELETE RESTRICT,
 FOREIGN KEY (verified_by) REFERENCES nd_admin(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_lc_milestone_versions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT UNSIGNED NOT NULL,
 stage_id BIGINT UNSIGNED NOT NULL,
 agreement_binding_id BIGINT UNSIGNED NOT NULL,
 revision_number INT UNSIGNED NOT NULL,
 evidence_json MEDIUMTEXT NOT NULL,
 checksum CHAR(64) NOT NULL,
 state ENUM('AWAITING_CLIENT','ACCEPTED','CHANGES_REQUESTED') NOT NULL,
 owner_verified_at DATETIME NOT NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY nd_lc_milestone_revision(stage_id,revision_number),
 FOREIGN KEY (order_id) REFERENCES nd_lc_order_flow(order_id) ON DELETE RESTRICT,
 FOREIGN KEY (stage_id) REFERENCES nd_project_stages(id) ON DELETE RESTRICT,
 FOREIGN KEY (agreement_binding_id) REFERENCES nd_lc_document_bindings(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_lc_feedback (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 milestone_version_id BIGINT UNSIGNED NOT NULL UNIQUE,
 account_id BIGINT UNSIGNED NOT NULL,
 kind ENUM('ACCEPT','DEFECT','INCLUDED_REVISION','EXTRA_SCOPE') NOT NULL,
 feedback TEXT NOT NULL,
 checksum CHAR(64) NOT NULL,
 state ENUM('OPEN','RESOLVED') NOT NULL DEFAULT 'OPEN',
 resolution TEXT NULL,
 resolution_version_id BIGINT UNSIGNED NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (milestone_version_id) REFERENCES nd_lc_milestone_versions(id) ON DELETE RESTRICT,
 FOREIGN KEY (account_id) REFERENCES nd_customer_accounts(id) ON DELETE RESTRICT,
 FOREIGN KEY (resolution_version_id) REFERENCES nd_lc_milestone_versions(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_lc_scope_changes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT UNSIGNED NOT NULL,
 actor_type ENUM('owner','customer') NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL,
 request_body TEXT NOT NULL,
 proposal_json MEDIUMTEXT NULL,
 checksum CHAR(64) NULL,
 owner_decision ENUM('ACCEPT','REJECT') NULL,
 client_decision ENUM('ACCEPT','REJECT') NULL,
 decision_reason TEXT NULL,
 agreement_binding_id BIGINT UNSIGNED NULL,
 applied_at DATETIME NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (order_id) REFERENCES nd_lc_order_flow(order_id) ON DELETE RESTRICT,
 FOREIGN KEY (agreement_binding_id) REFERENCES nd_lc_document_bindings(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_lc_business_decisions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT UNSIGNED NOT NULL,
 target_kind ENUM('PROPOSAL','FINAL','HANDOVER') NOT NULL,
 target_hash CHAR(64) NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL,
 decision ENUM('ACCEPT','DEFECT','INCLUDED_REVISION','EXTRA_SCOPE','REJECT') NOT NULL,
 reason TEXT NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY nd_lc_business_decision(order_id,target_kind,target_hash),
 FOREIGN KEY (order_id) REFERENCES nd_lc_order_flow(order_id) ON DELETE RESTRICT,
 FOREIGN KEY (actor_id) REFERENCES nd_customer_accounts(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
