CREATE TABLE nd_work_calendars (
 id TINYINT UNSIGNED PRIMARY KEY,
 daily_minutes SMALLINT UNSIGNED NOT NULL,
 weekdays_json VARCHAR(32) NOT NULL,
 exceptions_json MEDIUMTEXT NOT NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 reviewed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_task_planning (
 task_id BIGINT UNSIGNED PRIMARY KEY,
 estimate_minutes INT UNSIGNED NULL,
 earliest_on DATE NULL,
 dependencies_json MEDIUMTEXT NOT NULL,
 planned_start DATE NULL,
 planned_end DATE NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 FOREIGN KEY(task_id) REFERENCES nd_tasks(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_workload_plans (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 source_hash CHAR(64) NOT NULL,
 body_json MEDIUMTEXT NOT NULL,
 checksum CHAR(64) NOT NULL,
 applied_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
