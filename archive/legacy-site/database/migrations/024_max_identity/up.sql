CREATE TABLE nd_max_account_links (
 max_user_id BIGINT UNSIGNED PRIMARY KEY,
 account_id BIGINT UNSIGNED NOT NULL UNIQUE,
 linked_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(account_id) REFERENCES nd_customer_accounts(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_max_launches (
 proof_hash CHAR(64) PRIMARY KEY,
 nonce_hash CHAR(64) NOT NULL,
 expires_at BIGINT UNSIGNED NOT NULL,
 consumed_at BIGINT UNSIGNED NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_max_sessions (
 token_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 max_user_id BIGINT UNSIGNED NOT NULL,
 expires_at BIGINT UNSIGNED NOT NULL,
 FOREIGN KEY(token_hash) REFERENCES nd_customer_sessions(token_hash) ON DELETE CASCADE,
 FOREIGN KEY(max_user_id) REFERENCES nd_max_account_links(max_user_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE nd_max_account_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 max_user_id BIGINT UNSIGNED NOT NULL,
 account_id BIGINT UNSIGNED NOT NULL,
 action ENUM('LINKED','UNLINKED','LOGIN') NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
